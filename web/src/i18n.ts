export type Lang = 'zh-CN' | 'en';
export const DICTS: Record<Lang, Dict> = { en, 'zh-CN': zh };

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('loggy.lang');
    if (saved === 'en' || saved === 'zh-CN') return saved;
  } catch {
    // storage unavailable
  }
  return navigator.language?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

const plurals = new Map<Lang, Intl.PluralRules>();

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s: string = DICTS[lang][key] ?? DICTS.en[key] ?? key;
  if (s.includes('|') && vars && typeof vars.n === 'number') {
    // "one|other" forms, e.g. "{n} input|{n} inputs".
    let pr = plurals.get(lang);
    if (!pr) plurals.set(lang, (pr = new Intl.PluralRules(lang)));
    const [one, other] = s.split('|');
    s = pr.select(vars.n) === 'one' ? one : other;
  }
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export interface I18n {
  lang: Lang;
  t: (key: Key, vars?: Record<string, string | number>) => string;
}

export const I18nContext = createContext<I18n>({ lang: 'en', t: (k, v) => translate('en', k, v) });

export function useI18n(): I18n {
  return useContext(I18nContext);
}
